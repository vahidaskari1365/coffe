export type CategoryId = "roaster" | "grinder" | "extraction" | "packaging";

export type Category = {
  id: CategoryId;
  title: string;
  latin: string;
  description: string;
  icon: "flame" | "grind" | "drop" | "box";
};

export type Spec = { label: string; value: string };

export type Product = {
  id: string;
  slug: string;
  name: string;
  latin: string;
  category: CategoryId;
  tagline: string;
  description: string;
  highlights: string[];
  specs: Spec[];
  applications: string[];
  image: string;
  gallery: string[];
  badge?: string;
  featured?: boolean;
  capacity: string;
  power: string;
};

export type Block =
  | { type: "p"; text: string }
  | { type: "h"; text: string }
  | { type: "quote"; text: string; author?: string }
  | { type: "list"; items: string[] };

export type Article = {
  id: string;
  slug: string;
  title: string;
  category: string;
  excerpt: string;
  image: string;
  author: string;
  date: string;
  readTime: string;
  content: Block[];
};

export type Inquiry = {
  id: string;
  name: string;
  company: string;
  phone: string;
  email: string;
  product: string;
  capacity: string;
  message: string;
  source: string;
  status: "new" | "review" | "contacted" | "closed";
  createdAt: string;
};

export type Project = {
  id: string;
  slug: string;
  title: string;
  client: string;
  location: string;
  year: string;
  scope: string;
  summary: string;
  image: string;
  metrics: { value: string; label: string }[];
  tags: string[];
  featured?: boolean;
};

export type TechStage = {
  id: string;
  number: string;
  title: string;
  latin: string;
  description: string;
  image: string;
  bullets: string[];
  metric: string;
  metricLabel: string;
};

